export type EffectDepthLayer = 'behind' | 'beside' | 'front';

export interface ProductEffectItem {
  id: string;
  asset: string;
  alt: string;
  layer: EffectDepthLayer;
  /** Desktop size in px */
  size: number;
  /** Mobile size in px */
  mobileSize: number;
  /** Initial entrance offset (in px relative to product center) */
  initialX: number;
  initialY: number;
  /** Optional intermediate keyframe for curved paths or slow-motion separation */
  midX?: number;
  midY?: number;
  /** Settled position around the product perimeter (in px relative to product center) */
  targetX: number;
  targetY: number;
  /** Initial and target rotation in degrees */
  initialRotate: number;
  midRotate?: number;
  targetRotate: number;
  /** Scale progression */
  initialScale: number;
  midScale?: number;
  targetScale: number;
  /** Target resting opacity (0.84 - 1.0) */
  targetOpacity: number;
  /** Staggered delay in seconds (first element ~0.10s, followed by 60-110ms stagger) */
  delay: number;
  /** Entrance animation duration in seconds (0.78s - 1.22s) */
  duration: number;
  /** Continuous subtle multi-axis floating parameters after settling */
  floatX?: number;
  floatY: number;
  floatRotate: number;
  floatDuration: number;
  /** Optional CSS horizontal/vertical flip for natural organic variety */
  flipX?: boolean;
  /** Optional subtle depth blur in px for deep background or close macro elements */
  depthBlur?: number;
  /** Hide secondary particles on smaller mobile screens for clean composition */
  hideOnMobile?: boolean;
}

