export type EffectDepthLayer = 'behind' | 'beside' | 'front';

export interface ProductEffectItem {
  id: string;
  asset: string;
  alt: string;
  layer: EffectDepthLayer;
  /** Desktop size in px */
  size: number;
  /** Mobile size in px */
  mobileSize: number;
  /** Initial entrance offset in outer air (never inside the package silhouette) */
  initialX: number;
  initialY: number;
  /** Settled position around the outer perimeter of the product */
  targetX: number;
  targetY: number;
  /** Initial and target rotation in degrees */
  initialRotate: number;
  targetRotate: number;
  /** Scale progression (0.88–0.95 -> targetScale) */
  initialScale: number;
  targetScale: number;
  /** Staggered delay in seconds (first element 0.10s, followed by 60–70ms stagger) */
  delay: number;
  /** Entrance animation duration in seconds (0.54s–0.66s) */
  duration: number;
  /** Continuous subtle multi-axis floating parameters after settling */
  floatX: number;
  floatY: number;
  floatRotate: number;
  floatDuration: number;
  /** Optional CSS horizontal flip for natural variety */
  flipX?: boolean;
  /** Hide secondary accent on smaller mobile screens to keep mobile clean (3–4 items visible) */
  hideOnMobile?: boolean;
}

